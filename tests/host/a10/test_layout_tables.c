static const uint16_t	g_unknown[] = {0x00, 0x02, 0x08, 0x10, 0x13, 0x85,
	0xe0ff, 0xe021, 0xe010, 0xe037, 0xe03f, 0xe05e, 0xe012, 0xe059, 0xe0f0};

static void	common_vk_table(void)
{
	const t_key	*key;
	uint32_t	i;

	i = 0;
	while (i < sizeof(g_common) / sizeof(g_common[0]))
	{
		key = common_key(g_common[i].code);
		h_true(key != NULL, "touche commune presente");
		if (key)
		{
			h_eq_u64("code virtuel commun", key->vk, g_common[i].vk);
			h_eq_u64("code virtuel numerique", key->vk_num,
				g_common[i].vk_num);
		}
		i++;
	}
}

static void	unknown_keys_ignored(void)
{
	uint32_t	i;

	i = 0;
	while (i < sizeof(g_unknown) / sizeof(g_unknown[0]))
	{
		h_true(layout_key(&g_layout_fr, g_unknown[i]) == NULL,
			"touche inconnue fr");
		h_true(layout_key(&g_layout_us, g_unknown[i]) == NULL,
			"touche inconnue us");
		i++;
	}
}

int	main(void)
{
	h_begin("a10/layout_tables");
	h_run("tableau des touches communes", common_vk_table);
	h_run("touches inconnues ignorees", unknown_keys_ignored);
	return (h_end());
}
