#include "a16_test.h"

static const uint32_t	g_french[] = {
	0xC0, 0xC2, 0xC7, 0xC8, 0xC9, 0xCA, 0xCE, 0xD4,
	0xE0, 0xE2, 0xE7, 0xE8, 0xE9, 0xEA, 0xEB, 0xEE, 0xEF, 0xF4, 0xF9,
	0xFB, 0xFC, 0x153,
	0xA0, 0xAB, 0xBB, 0xB0, 0xB7, 0xD7, 0x2013, 0x2014, 0x2019, 0x2026,
	0xFFFD,
};
static const uint32_t	g_display[] = {
	0xC0, 0xC7, 0xC8, 0xC9, 0xCA,
	0xE0, 0xE2, 0xE7, 0xE8, 0xE9, 0xEA, 0xEB, 0xEE, 0xEF, 0xF4, 0xF9,
	0xFB, 0xFC, 0x153,
	0xA0, 0xAB, 0xBB, 0x2013, 0x2014, 0x2019, 0x2026,
	0xFFFD,
};
static const uint32_t	g_digits[] = {
	0x20, 0x30, 0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39, 0x3A,
	0xA0, 0xFFFD,
};
static const t_csetdef	g_defs[3] = {
{g_french, sizeof(g_french) / sizeof(g_french[0]), 1},
{g_display, sizeof(g_display) / sizeof(g_display[0]), 1},
{g_digits, sizeof(g_digits) / sizeof(g_digits[0]), 0},
};

t_cset	charset_of(t_fontid id)
{
	if (id == FONT_INS_SEMI_120)
		return (CS_DIGITS);
	if (id >= FONT_INS_BOLD_24 && id <= FONT_INS_BOLD_28)
		return (CS_DISPLAY);
	return (CS_FRENCH);
}

int	charset_has(t_cset set, uint32_t cp)
{
	const t_csetdef	*def;
	size_t			i;

	def = &g_defs[set];
	if (def->ascii && cp >= 0x20 && cp <= 0x7E)
		return (1);
	i = 0;
	while (i < def->len)
	{
		if (def->list[i] == cp)
			return (1);
		i++;
	}
	return (0);
}

int32_t	charset_count(t_cset set)
{
	int32_t	count;

	count = (int32_t)g_defs[set].len;
	if (g_defs[set].ascii)
		count += 0x7E - 0x20 + 1;
	return (count);
}
